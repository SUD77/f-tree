test('a living person shows the year they were born, and nothing more, unless asked', async () => {
  const doc = await sampleDoc();
  const living = doc.people.filter((p) => !p.deceased && !p.deathDate && /^\d{4}-\d{2}-\d{2}$/.test(p.birthDate ?? ''));
  assert.ok(living.length, 'the sample needs a living person with a full birth date');
  const months = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const full = (p) => { const [y, m, d] = p.birthDate.split('-'); return `${Number(d)} ${months[Number(m) - 1]} ${y}`; };

  const hidden = JSON.stringify(composeBook(doc, { now: NOW }, TEMPLATES.heirloom));
  for (const p of living) {
    assert.ok(!hidden.includes(full(p)), `${p.name}'s full birth date is in the book`);
    assert.ok(!hidden.includes(p.birthDate), `${p.name}'s ISO birth date is in the book`);
  }
  const shown = JSON.stringify(composeBook(doc, { now: NOW, livingDates: true }, TEMPLATES.heirloom));
  assert.ok(living.some((p) => shown.includes(full(p))), 'asking for full dates shows them');
});

test('no page gives a living person an age', async () => {
  const doc = JSON.parse(read('fixtures/remarriage.json'));
  const book = composeBook(doc, { now: NOW }, TEMPLATES.heirloom);
  const words = JSON.stringify(book);
  // Rekha (b. 1958) is living: 68 in 2026. The only "N years" allowed is a departed person's life.
  assert.ok(!/\b68 years\b/.test(words));
  assert.ok(/\b61 years\b/.test(words), "Harish's recorded life (1950-2011) is the longest");
});

test('an allowance of generations keeps that many, from the eldest down', async () => {
  const doc = await sampleDoc();
  const all = composeBook(doc, { now: NOW }, TEMPLATES.heirloom);
  const two = composeBook(doc, { now: NOW }, TEMPLATES.heirloom, { maxGenerations: 2 });
  assert.deepEqual(validateBook(two), []);
  assert.ok(JSON.stringify(two).length < JSON.stringify(all).length);
  assert.ok(!two.pages.some((p) => JSON.stringify(p).includes('The third generation')));
  assert.ok(two.pages.some((p) => JSON.stringify(p).includes('The second generation')));
});

