test('line breaking keeps within the width and never splits a word', () => {
  const m = METRICS.book_text;
  const s = 'Everyone in this book, and the page they are on, in the order a reader looks for them.';
  const lines = breakLines(s, m, 11, 150);
  assert.ok(lines.length > 1);
  for (const l of lines) assert.ok(measure(l, m, 11) <= 150 || !l.includes(' '), l);
  assert.equal(lines.join(' '), s);
  const cut = breakLines(s, m, 11, 150, 2);
  assert.equal(cut.length, 2);
  assert.ok(cut[1].endsWith('…'));
});

test('names sort the same on every engine, and Devanagari keeps its vowel signs', () => {
  const names = ['Émile', 'Aarav', 'zoya', 'Ishaan', 'कबीर', 'कुबेर'];
  const sorted = [...names].sort((a, b) => byKey(sortKey(a), sortKey(b)));
  assert.deepEqual(sorted, ['Aarav', 'Émile', 'Ishaan', 'zoya', 'कबीर', 'कुबेर']);
  assert.notEqual(sortKey('कबीर'), sortKey('कुबेर'));
});

test('the QR code on the closing page is the vendored encoder\'s own', () => {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(readFileSync(path.join(here, '../../desktop/renderer/vendor/qr.js'), 'utf8'), ctx);
  const qr = ctx.qrcode(0, 'M');
  qr.addData(SITE_URL);
  qr.make();
  const n = qr.getModuleCount();
  const rows = [];
  for (let r = 0; r < n; r++) { let s = ''; for (let c = 0; c < n; c++) s += qr.isDark(r, c) ? '1' : '0'; rows.push(s); }
  assert.deepEqual(SITE_QR, rows);
});

test('the SVG painter draws every page of every book', async () => {
  for (const [name, load] of Object.entries(FIXTURES)) {
    const doc = await load();
    const book = composeBook(doc, { now: NOW }, TEMPLATES.diwali);
    book.pages.forEach((_, i) => {
      const svg = paintPage(book, i, { photo: () => 'data:image/jpeg;base64,', font: (k) => k });
      assert.ok(svg.startsWith('<svg') && svg.endsWith('</svg>'), `${name} page ${i + 1}`);
      assert.ok(!/NaN|undefined|Infinity/.test(svg), `${name} page ${i + 1} holds a non-number`);
      const ids = [...svg.matchAll(/ id="([^"]+)"/g)].map((m) => m[1]);
      assert.equal(new Set(ids).size, ids.length, `${name} page ${i + 1} repeats an id`);
      for (const [, ref] of svg.matchAll(/url\(#([^)]+)\)/g)) assert.ok(ids.includes(ref), `${name} page ${i + 1}: #${ref}`);
    });
  }
});

