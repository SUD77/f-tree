const here = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(path.join(here, p), 'utf8');
const UPDATE = process.env.UPDATE_GOLDEN === '1';
const NOW = '2026-09-15';

const TEMPLATES = { heirloom: JSON.parse(read('templates/heirloom.json')), diwali: JSON.parse(read('templates/diwali.json')) };

async function sampleDoc() {
  const buf = readFileSync(path.join(here, '../playground/sample-family.ftree'));
  const archive = await openArchive(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  return parseDocument(await archive.readText('tree.json'));
}

const FIXTURES = {
  sample: sampleDoc,
  devanagari: async () => JSON.parse(read('fixtures/devanagari.json')),
  large: async () => JSON.parse(read('fixtures/large.json')),
  remarriage: async () => JSON.parse(read('fixtures/remarriage.json')),
  'one-person': async () => JSON.parse(read('fixtures/one-person.json')),
  empty: async () => JSON.parse(read('fixtures/empty.json')),
};

const hash = (book) => createHash('sha256').update(JSON.stringify(book)).digest('hex').slice(0, 16);

test('every fixture composes into a valid book with every template', async () => {
  const lines = [];
  for (const [name, load] of Object.entries(FIXTURES)) {
    const doc = await load();
    for (const [tid, tpl] of Object.entries(TEMPLATES)) {
      const book = composeBook(doc, { now: NOW }, tpl);
      assert.deepEqual(validateBook(book), [], `${name}/${tid}`);
      assert.equal(book.pages[0].label, 'Cover');
      assert.equal(book.pages.at(-1).label, 'Is someone missing?');
      lines.push(`${name} ${tid} ${hash(book)} ${book.pages.length} ${book.pages.map((p) => p.label.replace(/ /g, '_')).join(',')}`);
    }
  }
  const golden = path.join(here, 'golden.txt');
  const text = `# Generated by book.test.mjs. Regenerate with UPDATE_GOLDEN=1 once a change is intended.\n${lines.join('\n')}\n`;
  if (UPDATE) writeFileSync(golden, text);
  assert.equal(text, readFileSync(golden, 'utf8'), 'a book changed - if that was intended, UPDATE_GOLDEN=1');
});

test('the full golden book is what the composer makes today', async () => {
  const book = composeBook(await sampleDoc(), { now: NOW }, TEMPLATES.heirloom);
  const file = path.join(here, 'golden/sample-heirloom.json');
  if (UPDATE) { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, JSON.stringify(book)); }
  assert.equal(JSON.stringify(book), readFileSync(file, 'utf8'));
});

