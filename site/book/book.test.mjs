/*
 * The composer, held to what the book promises.
 *
 * Goldens: golden.txt holds one line per fixture and template - a hash of the Book the composer
 * makes, and its page list. Any change to what a book looks like changes a hash, so a layout change
 * is a decision somebody makes (UPDATE_GOLDEN=1 node --test site/book/book.test.mjs), never a drift
 * nobody noticed. golden/sample-heirloom.json is the one book written out in full: the Android app's
 * JVM tests parse it, so the Kotlin model is proved against real composer output.
 */

